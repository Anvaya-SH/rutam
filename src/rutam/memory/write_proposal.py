"""Structured memory write proposals, operation definitions, and output dataclasses."""

from __future__ import annotations

import math
import uuid
from dataclasses import dataclass, field
from datetime import datetime
from enum import IntEnum
from typing import Any

import torch

from rutam.config import nonempty_string, positive_int
from rutam.exceptions import ValidationError
from rutam.graph.embeddings import require_finite, validate_tensor
from rutam.graph.schema import identifier, timestamp, utc_now
from rutam.memory.provenance import ProvenanceRecord


class MemoryOperation(IntEnum):
    """Stable versioned mapping of supported memory operations."""

    NO_OP = 0
    CREATE_NODE = 1
    UPDATE_NODE = 2
    PROPOSE_LINK = 3
    PROPOSE_MERGE = 4
    SUPERSEDE_NODE = 5
    REQUEST_VALIDATION = 6
    DELETE_NODE = 7
    DELETE_LINK = 8

    # Short names kept as aliases for callers using the operation vocabulary
    # from the architecture spec. The numeric values above remain stable.
    ADD_NODE = CREATE_NODE
    UPDATE = UPDATE_NODE
    LINK = PROPOSE_LINK
    DELETE = DELETE_NODE

    @classmethod
    def from_value(cls, val: object) -> MemoryOperation:
        if isinstance(val, MemoryOperation):
            return val
        if isinstance(val, int) and not isinstance(val, bool):
            try:
                return cls(val)
            except ValueError as exc:
                raise ValidationError(f"Unknown memory operation code: {val}") from exc
        if isinstance(val, str):
            try:
                return cls[val.strip().upper()]
            except KeyError as exc:
                raise ValidationError(f"Unknown memory operation name: {val}") from exc
        raise ValidationError(f"Cannot convert {type(val).__name__} to MemoryOperation")


@dataclass(frozen=True, slots=True)
class MemoryProposal:
    """Structured, immutable memory proposal generated by RUTAMMemoryWriteHead.

    Proposals represent neural intent and require downstream validation and
    transactional commits before modifying persistent graph state.
    """

    proposal_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    operation: MemoryOperation | str = MemoryOperation.CREATE_NODE
    candidate_embedding: torch.Tensor | None = None
    target_node_ids: tuple[int, ...] = ()
    proposed_link_ids: tuple[int, ...] = ()
    provenance: ProvenanceRecord | dict[str, Any] | str = field(default_factory=dict)
    confidence: float = 1.0
    source_graph_version: int | None = None
    timestamp: datetime = field(default_factory=utc_now)
    origin_category: str = "neural_write_head"
    validation_status: str = "pending"
    content: str | None = None
    node_type: str | None = None
    relation_type: str | None = None
    scope: str = "default"
    owner_id: str | None = None

    def __post_init__(self) -> None:
        nonempty_string(self.proposal_id, "proposal_id")
        op = MemoryOperation.from_value(self.operation)
        object.__setattr__(self, "operation", op)
        if self.candidate_embedding is not None:
            validate_tensor(self.candidate_embedding, "candidate_embedding", torch.float32)
            if self.candidate_embedding.ndim != 1:
                raise ValidationError("candidate_embedding must be a 1D tensor [H]")
            require_finite(self.candidate_embedding, "candidate_embedding")
            object.__setattr__(self, "candidate_embedding", self.candidate_embedding.detach().cpu().clone())
        if not isinstance(self.target_node_ids, (tuple, list)):
            raise ValidationError("target_node_ids must be a sequence of integers")
        for tid in self.target_node_ids:
            identifier(tid, "target_node_id")
        object.__setattr__(self, "target_node_ids", tuple(self.target_node_ids))
        if not isinstance(self.proposed_link_ids, (tuple, list)):
            raise ValidationError("proposed_link_ids must be a sequence of integers")
        for lid in self.proposed_link_ids:
            positive_int(lid, "proposed_link_id", minimum=0)
        object.__setattr__(self, "proposed_link_ids", tuple(self.proposed_link_ids))
        if len(set(self.target_node_ids)) != len(self.target_node_ids):
            raise ValidationError("target_node_ids must not contain duplicates")
        if self.content is not None and not isinstance(self.content, str):
            raise ValidationError("content must be a string or None")
        if self.node_type is not None:
            nonempty_string(self.node_type, "node_type")
        if self.relation_type is not None:
            nonempty_string(self.relation_type, "relation_type")
        nonempty_string(self.scope, "scope")
        if self.owner_id is not None:
            nonempty_string(self.owner_id, "owner_id")
        if isinstance(self.confidence, bool) or not isinstance(self.confidence, (int, float)):
            raise ValidationError("confidence must be a float")
        if not math.isfinite(self.confidence) or not 0.0 <= self.confidence <= 1.0:
            raise ValidationError("confidence must be a finite float in [0.0, 1.0]")
        if self.source_graph_version is not None:
            positive_int(self.source_graph_version, "source_graph_version", minimum=0)
        timestamp(self.timestamp, "timestamp")
        nonempty_string(self.origin_category, "origin_category")
        nonempty_string(self.validation_status, "validation_status")
        if not isinstance(self.provenance, (ProvenanceRecord, dict, str)):
            raise ValidationError("provenance must be a ProvenanceRecord, dict, or str")

    def to_dict(self) -> dict[str, Any]:
        emb = self.candidate_embedding.tolist() if self.candidate_embedding is not None else None
        prov = (
            self.provenance.to_dict()
            if isinstance(self.provenance, ProvenanceRecord)
            else self.provenance
        )
        return {
            "proposal_id": self.proposal_id,
            "operation": self.operation.name,
            "candidate_embedding": emb,
            "target_node_ids": list(self.target_node_ids),
            "proposed_link_ids": list(self.proposed_link_ids),
            "provenance": prov,
            "confidence": self.confidence,
            "source_graph_version": self.source_graph_version,
            "timestamp": self.timestamp.isoformat(),
            "origin_category": self.origin_category,
            "validation_status": self.validation_status,
            "content": self.content,
            "node_type": self.node_type,
            "relation_type": self.relation_type,
            "scope": self.scope,
            "owner_id": self.owner_id,
        }

    @property
    def expected_graph_version(self) -> int | None:
        """Explicit concurrency name for the proposal's source snapshot version."""
        return self.source_graph_version


@dataclass(frozen=True, slots=True)
class MemoryWriteOutput:
    """Typed outputs produced by RUTAMMemoryWriteHead.

    write_logits: [B, 1] raw unmasked logits for BCEWithLogits supervision.
    write_probabilities: [B, 1] sigmoid probabilities masked by availability.
    operation_logits: [B, O] raw logits over operation classes.
    operation_probabilities: [B, O] softmax probabilities over operations.
    proposed_embeddings: [B, M, H] candidate memory vectors.
    target_memory_scores: optional [B, K] compatibility scores for candidate nodes.
    proposal_mask: [B, M] boolean mask indicating valid proposals.
    write_decisions: optional [B] boolean decisions in inference/eval mode.
    proposals: nested batch proposals [B][P] of MemoryProposal instances.
    """

    write_logits: torch.Tensor
    write_probabilities: torch.Tensor
    operation_logits: torch.Tensor
    operation_probabilities: torch.Tensor
    proposed_embeddings: torch.Tensor
    target_memory_scores: torch.Tensor | None
    proposal_mask: torch.Tensor
    write_decisions: torch.Tensor | None
    proposals: tuple[tuple[MemoryProposal, ...], ...] = ()
